const km = (a, b) => {
  const r = Math.PI / 180, x = (b[1] - a[1]) * r * Math.cos(((a[0] + b[0]) / 2) * r), y = (b[0] - a[0]) * r
  return 6371 * Math.hypot(x, y)
}
export const HASHIMOTO = [35.5946, 139.345]
export const distKm = km
export function areaOfPoint(p) {
  let best = null
  for (const a of AREAS) { const d = km(a.c, p); if (d <= a.r && (!best || d < best.d)) best = { a, d } }
  return best?.a.name ?? null
}
// 掲載項目の place から街を判定（area → station → name の順に見る）
export function areaOfPlace(place) {
  for (const s of [place?.area, place?.station, place?.name]) {
    if (!s) continue
    const hit = AREAS.find((a) => a.aliases.some((x) => s.includes(x)))
    if (hit) return hit.name
  }
  return null
}
